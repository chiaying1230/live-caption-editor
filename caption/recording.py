"""Persist the same PCM frames used by ASR, including silence, as local WAVs."""
import wave
import sqlite3
from pathlib import Path


class RecordingError(OSError):
    pass


class AudioArchive:
    def __init__(self, store, directory):
        self.store, self.directory = store, Path(directory)
        self.directory.mkdir(parents=True, exist_ok=True)
        # WAV headers are updated for each frame. Recover completed frames after
        # an interrupted process instead of leaving recordings permanently busy.
        for row in store.audio_recordings(unfinished=True):
            samples = row['samples']
            try:
                with wave.open(str(self.path(row['id'])), 'rb') as audio:
                    samples = audio.getnframes()
            except (OSError, EOFError, wave.Error):
                pass
            store.update_recording(row['id'], samples, 'interrupted')

    def path(self, rid):
        # IDs are generated by Store; callers first look them up within a session.
        return self.directory / f'{rid}.wav'

    def start(self, sid, offset):
        return WavRecording(self, self.store.begin_recording(sid, offset))


class WavRecording:
    def __init__(self, archive, row):
        self.archive, self.row = archive, row
        self.samples = 0
        self.closed = False
        self.file = None
        try:
            self.file = archive.path(row['id']).open('xb', buffering=0)
            self.audio = wave.open(self.file, 'wb')
            self.audio.setparams((1, 2, 16000, 0, 'NONE', 'not compressed'))
            self.audio.writeframes(b'')
        except OSError as exc:
            if self.file:
                self.file.close()
                try:
                    archive.path(row['id']).unlink(missing_ok=True)
                except OSError:
                    pass
            archive.store.discard_recording(row['id'])
            raise RecordingError('Cannot create the recording file') from exc

    def write(self, pcm):
        if len(pcm) != 3200:
            raise ValueError('音訊格式錯誤：需要 16 kHz mono PCM16，每包 100 ms。')
        try:
            # writeframes updates the RIFF/data lengths, and unbuffered output
            # keeps already received frames readable without accumulating RAM.
            self.audio.writeframes(pcm)
        except (OSError, wave.Error) as exc:
            raise RecordingError('Cannot save microphone audio') from exc
        self.samples += len(pcm) // 2
        if self.samples % 16000 == 0:
            try:
                self.archive.store.update_recording(self.row['id'], self.samples)
            except sqlite3.Error as exc:
                raise RecordingError('Cannot save recording metadata') from exc

    def finish(self, *, interrupted=False):
        if self.closed:
            return
        self.closed = True
        try:
            self.audio.close()
        except (OSError, wave.Error) as exc:
            interrupted = True
            raise RecordingError('Cannot finalize microphone audio') from exc
        finally:
            self.file.close()
            if not self.samples:
                self.archive.path(self.row['id']).unlink(missing_ok=True)
                self.archive.store.discard_recording(self.row['id'])
            else:
                self.archive.store.update_recording(
                    self.row['id'], self.samples, 'interrupted' if interrupted else 'complete')
